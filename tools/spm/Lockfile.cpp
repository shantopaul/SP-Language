std::string Lockfile::trim(const std::string& s) {
    size_t start = 0;
    while (start < s.size() && std::isspace(static_cast<unsigned char>(s[start]))) {
        start++;
    }
    size_t end = s.size();
    while (end > start && std::isspace(static_cast<unsigned char>(s[end - 1]))) {
        end--;
    }
    return s.substr(start, end - start);
}

std::string Lockfile::stripQuotes(const std::string& s) {
    std::string t = trim(s);
    if (t.size() >= 2 && ((t.front() == '"' && t.back() == '"') || (t.front() == '\'' && t.back() == '\''))) {
        return t.substr(1, t.size() - 2);
    }
    return t;
}

Lockfile Lockfile::fromResolution(const ResolutionResult& res) {
    Lockfile lock;
    lock.m_version = 1;

    for (const auto& pkg : res.resolvedPackages) {
        LockedPackage locked;
        locked.name = pkg.name;
        locked.version = pkg.version.toString();
        if (pkg.sourceKind == PackageSourceKind::Path) {
            locked.source = "path:" + pkg.sourceLocation;
        } else if (pkg.sourceKind == PackageSourceKind::Git) {
            locked.source = "git:" + pkg.sourceLocation;
        } else {
            locked.source = "registry";
        }
        locked.checksum = pkg.checksum;
        locked.dependencies = pkg.dependencies;
        lock.m_packages.push_back(std::move(locked));
    }

    return lock;
}

const LockedPackage* Lockfile::findPackage(const std::string& name) const {
    for (const auto& pkg : m_packages) {
        if (pkg.name == name) {
            return &pkg;
        }
    }
    return nullptr;
}

bool Lockfile::isUpToDate(const ProjectConfig& config) const {
    for (const auto& dep : config.getDependencies()) {
        const auto* locked = findPackage(dep.name);
        if (!locked) {
            return false;
        }

        auto lockedVer = Version::parse(locked->version);
        if (!lockedVer) {
            return false;
        }

        auto req = VersionReq::parse(dep.versionReq);
        if (!req || !req->matches(*lockedVer)) {
            return false;
        }
    }
    return true;
}

std::string Lockfile::toTomlString() const {
    std::ostringstream oss;
    oss << "# This file is automatically generated by SPM. Do not edit manually.\n";
    oss << "version = " << m_version << "\n\n";

    for (const auto& pkg : m_packages) {
        oss << "[[package]]\n";
        oss << "name = \"" << pkg.name << "\"\n";
        oss << "version = \"" << pkg.version << "\"\n";
        oss << "source = \"" << pkg.source << "\"\n";
        oss << "checksum = \"" << pkg.checksum << "\"\n";
        oss << "dependencies = [\n";
        for (const auto& d : pkg.dependencies) {
            oss << "    \"" << d << "\",\n";
        }
        oss << "]\n\n";
    }

    return oss.str();
}

bool Lockfile::saveToFile(const std::string& filePath) const {
    std::ofstream out(filePath);
    if (!out.is_open()) {
        m_lastError = "Failed to open file for writing: " + filePath;
        return false;
    }
    out << toTomlString();
    return true;
}

bool Lockfile::loadFromFile(const std::string& filePath) {
    std::ifstream in(filePath);
    if (!in.is_open()) {
        m_lastError = "Failed to open file for reading: " + filePath;
        return false;
    }
    std::stringstream buffer;
    buffer << in.rdbuf();
    return loadFromString(buffer.str());
}

bool Lockfile::loadFromString(const std::string& content) {
    m_packages.clear();
    m_version = 1;

    std::istringstream stream(content);
    std::string line;
    LockedPackage currentPkg;
    bool inPackage = false;
    bool inDepsArray = false;

    auto flushPackage = [&]() {
        if (inPackage && !currentPkg.name.empty()) {
            m_packages.push_back(currentPkg);
            currentPkg = LockedPackage{};
        }
    };

    while (std::getline(stream, line)) {
        std::string trimmed = trim(line);
        if (trimmed.empty() || trimmed.front() == '#') {
            continue;
        }

        if (inDepsArray) {
            if (trimmed.find(']') != std::string::npos) {
                inDepsArray = false;
                // Parse any items before ']' on this line if any
                size_t bracketPos = trimmed.find(']');
                std::string items = trimmed.substr(0, bracketPos);
                std::stringstream itemStream(items);
                std::string item;
                while (std::getline(itemStream, item, ',')) {
                    std::string clean = stripQuotes(item);
                    if (!clean.empty()) {
                        currentPkg.dependencies.push_back(clean);
                    }
                }
            } else {
                std::stringstream itemStream(trimmed);
                std::string item;
                while (std::getline(itemStream, item, ',')) {
                    std::string clean = stripQuotes(item);
                    if (!clean.empty()) {
                        currentPkg.dependencies.push_back(clean);
                    }
                }
            }
            continue;
        }

        if (trimmed == "[[package]]") {
            flushPackage();
            inPackage = true;
            currentPkg = LockedPackage{};
            continue;
        }

        size_t eqPos = trimmed.find('=');
        if (eqPos == std::string::npos) {
            continue;
        }

        std::string key = trim(trimmed.substr(0, eqPos));
        std::string val = trim(trimmed.substr(eqPos + 1));

        if (!inPackage) {
            if (key == "version") {
                try {
                    m_version = std::stoi(val);
                } catch (...) {
                    m_version = 1;
                }
            }
            continue;
        }

        if (key == "name") {
            currentPkg.name = stripQuotes(val);
        } else if (key == "version") {
            currentPkg.version = stripQuotes(val);
        } else if (key == "source") {
            currentPkg.source = stripQuotes(val);
        } else if (key == "checksum") {
            currentPkg.checksum = stripQuotes(val);
        } else if (key == "dependencies") {
            if (val.front() == '[' && val.back() == ']') {
                // Inline array: e.g. ["dep1", "dep2"]
                std::string inner = val.substr(1, val.size() - 2);
                std::stringstream itemStream(inner);
                std::string item;
                while (std::getline(itemStream, item, ',')) {
                    std::string clean = stripQuotes(item);
                    if (!clean.empty()) {
                        currentPkg.dependencies.push_back(clean);
                    }
                }
            } else if (val.front() == '[') {
                inDepsArray = true;
            }
        }
    }

    flushPackage();
    return true;
}

